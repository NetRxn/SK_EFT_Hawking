def test_bearer_revoke_is_quiescent_idempotent_and_prevents_token_reuse(adr018_repo) -> None:
    controller, _, _, _ = adr018_repo
    controller.inventory.raw["server"]["client_auth"] = "bearer"
    old = controller.inventory.token("chat")
    controller.acquire(1, client="chat", base_ref="main")
    with pytest.raises(SlotError, match="live lease"):
        controller.revoke_client_token(client="chat")
    assert controller.inventory.client_token_path("chat").exists()
    controller.release(1)
    assert controller.revoke_client_token(client="chat") == {
        "client": "chat",
        "revoked": True,
    }
    assert controller.revoke_client_token(client="chat") == {
        "client": "chat",
        "revoked": False,
    }
    fresh = controller.inventory.token("chat")
    assert fresh != old


