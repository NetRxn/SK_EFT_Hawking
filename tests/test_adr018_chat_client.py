def _write_inventory(path: Path, value: dict) -> Inventory:
    path.write_text(json.dumps(value))
    return Inventory.load(path)


def test_shipped_public_inventory_explicitly_admits_chat() -> None:
    inventory = Inventory.load()
    assert inventory.allowed_clients == frozenset({"codex", "claude", "chat"})


def test_schema1_missing_roster_is_exact_legacy_pair(adr018_repo) -> None:
    _, _, _, path = adr018_repo
    value = json.loads(path.read_text())
    del value["server"]["allowed_clients"]
    legacy = _write_inventory(path, value)
    assert legacy.allowed_clients == frozenset({"codex", "claude"})
    with pytest.raises(SlotError, match="not admitted"):
        legacy.require_allowed_client("chat")


@pytest.mark.parametrize(
    "roster,pattern",
    [
        ([], "non-empty"),
        (["codex", "codex"], "duplicates"),
        (["codex", "bad/client"], "invalid client name"),
        (["codex", 7], "entries must be strings"),
    ],
)
def test_inventory_rejects_invalid_client_rosters(adr018_repo, roster, pattern) -> None:
    _, _, _, path = adr018_repo
    value = json.loads(path.read_text())
    value["server"]["allowed_clients"] = roster
    path.write_text(json.dumps(value))
    with pytest.raises(SlotError, match=pattern):
        Inventory.load(path)


