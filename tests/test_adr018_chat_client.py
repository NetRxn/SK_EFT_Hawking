def test_removal_preflight_reports_live_client_without_mutating_lease(adr018_repo) -> None:
    controller, _, _, _ = adr018_repo
    controller.acquire(1, client="chat", base_ref="main")
    lease_path = controller.inventory.lease_path(1)
    before = lease_path.read_bytes()
    result = controller.removal_preflight(client="chat")
    assert not result["ok"]
    assert result["mismatches"] == [
        {"slot": 1, "client": "chat", "state": "ACQUIRED", "repo_role": "public"}
    ]
    assert lease_path.read_bytes() == before
    controller.release(1)
    assert controller.removal_preflight(client="chat")["ok"]


